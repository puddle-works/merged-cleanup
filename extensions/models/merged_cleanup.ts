/** The PRs a run was asked about, for its first log line. */
function asked(args: RunArgs): string {
  let numbers: number[];
  try {
    numbers = prNumbers(args.pr, args.prs);
  } catch {
    return `pr ${args.pr}, prs "${args.prs}"`;
  }
  return numbers.length
    ? `PRs ${numbers.join(", ")}`
    : `the latest ${LATEST} merged PRs`;
}

